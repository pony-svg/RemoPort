//! Physical keyboard mapping and state machine for Remoport.
//!
//! Maps Linux evdev key codes to RDP scancodes (set 1), enforces a single
//! source of truth for held keys, correlates physical Ctrl+V with clipboard
//! paste events, and manages focus and shortcuts.

use std::collections::HashSet;
use std::time::{Duration, Instant};

use crate::keymap::Scancode;

/// Time window to correlate physical V press with an egui Paste event.
/// 150 ms is imperceptible to users typing but comfortably absorbs UI frame latency.
pub const PASTE_CORRELATION_TIMEOUT: Duration = Duration::from_millis(150);

/// Action generated by the input state machine to be executed by the session.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum InputAction {
    /// Send a key stroke to the remote PC.
    SendKey {
        scancode: u8,
        extended: bool,
        pressed: bool,
    },
    /// Paste clipboard text into the remote PC.
    Paste(String),
    /// Local shortcut to toggle full screen (Ctrl+Alt+Enter).
    ToggleFullscreen,
}

/// Linux evdev key code to RDP set-1 scancode `(code, extended)`.
///
/// Returns `None` for keys that:
/// - do not have an RDP scancode mapping;
/// - are lock keys (Caps Lock, Num Lock, Scroll Lock: evdev 58, 69, 70), which
///   are handled via `Command::LockKeys` from Wayland modifier states;
/// - require complex multi-byte escape sequences like Pause/Break (evdev 119,
///   sequence `E1 1D 45`), which do not fit in a 2-byte [`Scancode`].
#[must_use]
pub fn scancode_from_evdev(evdev: u32) -> Option<Scancode> {
    let plain = |code: u8| Some((code, false));
    let extended = |code: u8| Some((code, true));

    match evdev {
        // Main block - Top row
        1 => plain(0x01),  // Escape
        2 => plain(0x02),  // 1
        3 => plain(0x03),  // 2
        4 => plain(0x04),  // 3
        5 => plain(0x05),  // 4
        6 => plain(0x06),  // 5
        7 => plain(0x07),  // 6
        8 => plain(0x08),  // 7
        9 => plain(0x09),  // 8
        10 => plain(0x0A), // 9
        11 => plain(0x0B), // 0
        12 => plain(0x0C), // Minus / Underscore
        13 => plain(0x0D), // Equals / Plus
        14 => plain(0x0E), // Backspace

        // Main block - QWERTY row
        15 => plain(0x0F), // Tab
        16 => plain(0x10), // Q
        17 => plain(0x11), // W
        18 => plain(0x12), // E
        19 => plain(0x13), // R
        20 => plain(0x14), // T
        21 => plain(0x15), // Y
        22 => plain(0x16), // U
        23 => plain(0x17), // I
        24 => plain(0x18), // O
        25 => plain(0x19), // P
        26 => plain(0x1A), // [ {
        27 => plain(0x1B), // ] }
        28 => plain(0x1C), // Enter

        // Main block - Home row
        29 => plain(0x1D), // Left Ctrl
        30 => plain(0x1E), // A
        31 => plain(0x1F), // S
        32 => plain(0x20), // D
        33 => plain(0x21), // F
        34 => plain(0x22), // G
        35 => plain(0x23), // H
        36 => plain(0x24), // J
        37 => plain(0x25), // K
        38 => plain(0x26), // L
        39 => plain(0x27), // ; :
        40 => plain(0x28), // ' "
        41 => plain(0x29), // ` ~

        // Main block - Bottom row
        42 => plain(0x2A), // Left Shift
        43 => plain(0x2B), // \ |
        44 => plain(0x2C), // Z
        45 => plain(0x2D), // X
        46 => plain(0x2E), // C
        47 => plain(0x2F), // V
        48 => plain(0x30), // B
        49 => plain(0x31), // N
        50 => plain(0x32), // M
        51 => plain(0x33), // , <
        52 => plain(0x34), // . >
        53 => plain(0x35), // / ?
        54 => plain(0x36), // Right Shift
        56 => plain(0x38), // Left Alt
        57 => plain(0x39), // Space
        86 => plain(0x56), // 102nd key (ISO extra key, typically \ or <)

        // Function keys F1 - F10
        59 => plain(0x3B), // F1
        60 => plain(0x3C), // F2
        61 => plain(0x3D), // F3
        62 => plain(0x3E), // F4
        63 => plain(0x3F), // F5
        64 => plain(0x40), // F6
        65 => plain(0x41), // F7
        66 => plain(0x42), // F8
        67 => plain(0x43), // F9
        68 => plain(0x44), // F10
        87 => plain(0x57), // F11
        88 => plain(0x58), // F12

        // Keypad block
        55 => plain(0x37),    // Keypad * (unextended 0x37)
        71 => plain(0x47),    // Keypad 7 / Home
        72 => plain(0x48),    // Keypad 8 / Up
        73 => plain(0x49),    // Keypad 9 / PgUp
        74 => plain(0x4A),    // Keypad -
        75 => plain(0x4B),    // Keypad 4 / Left
        76 => plain(0x4C),    // Keypad 5
        77 => plain(0x4D),    // Keypad 6 / Right
        78 => plain(0x4E),    // Keypad +
        79 => plain(0x4F),    // Keypad 1 / End
        80 => plain(0x50),    // Keypad 2 / Down
        81 => plain(0x51),    // Keypad 3 / PgDn
        82 => plain(0x52),    // Keypad 0 / Ins
        83 => plain(0x53),    // Keypad . / Del
        96 => extended(0x1C), // Keypad Enter
        98 => extended(0x35), // Keypad /

        // Navigation block
        102 => extended(0x47), // Home
        103 => extended(0x48), // Up
        104 => extended(0x49), // Page Up
        105 => extended(0x4B), // Left
        106 => extended(0x4D), // Right
        107 => extended(0x4F), // End
        108 => extended(0x50), // Down
        109 => extended(0x51), // Page Down
        110 => extended(0x52), // Insert
        111 => extended(0x53), // Delete

        // Right modifiers and system keys
        97 => extended(0x1D),  // Right Ctrl
        99 => extended(0x37),  // Print Screen (extended 0x37)
        100 => extended(0x38), // Right Alt / AltGr
        125 => extended(0x5B), // Left Windows / Meta
        126 => extended(0x5C), // Right Windows / Meta
        127 => extended(0x5D), // Menu / Apps

        // Lock keys (58 Caps, 69 Num, 70 Scroll) and Pause (119) do not produce scancodes.
        _ => None,
    }
}

/// Whether a key is a desktop-reserved key (Windows/Meta, Menu).
#[must_use]
pub fn is_desktop_reserved(evdev: u32) -> bool {
    matches!(evdev, 125..=127)
}

/// Pending physical 'V' press waiting for an egui paste text event.
#[derive(Debug, Clone, Copy)]
struct PendingV {
    press_time: Instant,
    released: bool,
}

/// Single owner of keyboard state across physical (Wayland) and egui fallbacks.
#[derive(Debug)]
pub struct KeyState {
    /// Keys currently sent as pressed to the PC.
    held: HashSet<Scancode>,
    /// Keys that were already held down when the window received focus (ignored until release).
    ignored_on_enter: HashSet<u32>,
    /// State of Ctrl keys (left evdev 29 or right evdev 97).
    ctrl_held: bool,
    /// State of Alt keys (left evdev 56 or right evdev 100).
    alt_held: bool,
    /// Pending physical V key press waiting for egui Paste.
    pending_v: Option<PendingV>,
    /// Cached Paste event waiting for physical V.
    pending_paste: Option<(String, Instant)>,
    /// Whether the session window is in full screen mode.
    fullscreen: bool,
    /// Whether clipboard sharing is enabled for this session.
    share_clipboard: bool,
}

impl KeyState {
    /// Creates a new key state machine.
    #[must_use]
    pub fn new(fullscreen: bool, share_clipboard: bool) -> Self {
        Self {
            held: HashSet::new(),
            ignored_on_enter: HashSet::new(),
            ctrl_held: false,
            alt_held: false,
            pending_v: None,
            pending_paste: None,
            fullscreen,
            share_clipboard,
        }
    }

    /// Sets whether the session is in full screen.
    pub fn set_fullscreen(&mut self, fullscreen: bool) {
        self.fullscreen = fullscreen;
    }

    /// Sets whether clipboard sharing is active.
    pub fn set_share_clipboard(&mut self, share: bool) {
        self.share_clipboard = share;
    }

    /// Called when the window receives keyboard focus from Wayland (`wl_keyboard.enter`).
    pub fn handle_enter(&mut self, pre_pressed_keys: &[u32]) {
        self.ignored_on_enter.clear();
        for &k in pre_pressed_keys {
            self.ignored_on_enter.insert(k);
        }
    }

    /// Called when keyboard focus is lost (`wl_keyboard.leave` or session unfocused).
    /// Releases all keys currently held on the PC.
    pub fn handle_leave(&mut self) -> Vec<InputAction> {
        self.ignored_on_enter.clear();
        self.pending_v = None;
        self.pending_paste = None;
        self.ctrl_held = false;
        self.alt_held = false;

        let mut actions = Vec::new();
        for (scancode, extended) in std::mem::take(&mut self.held) {
            actions.push(InputAction::SendKey {
                scancode,
                extended,
                pressed: false,
            });
        }
        actions
    }

    /// Processes an incoming physical key event from Wayland.
    pub fn handle_physical_key(
        &mut self,
        evdev: u32,
        pressed: bool,
        now: Instant,
    ) -> Vec<InputAction> {
        let mut actions = Vec::new();

        // Expire any stale pending Paste or flush pending V if timed out.
        actions.extend(self.flush_pending(now));

        // If the key was already pressed when entering focus, ignore it and its release.
        if !pressed && self.ignored_on_enter.remove(&evdev) {
            return actions;
        }
        if pressed && self.ignored_on_enter.contains(&evdev) {
            return actions;
        }

        // Track Ctrl and Alt for shortcuts and clipboard paste correlation.
        if matches!(evdev, 29 | 97) {
            self.ctrl_held = pressed;
        }
        if matches!(evdev, 56 | 100) {
            self.alt_held = pressed;
        }

        // Check local shortcut: Ctrl + Alt + Enter (evdev 28 or 96).
        if pressed && (evdev == 28 || evdev == 96) && self.ctrl_held && self.alt_held {
            actions.push(InputAction::ToggleFullscreen);
            return actions;
        }

        // Desktop-reserved keys (Windows, Menu) are ignored in windowed mode.
        if is_desktop_reserved(evdev) && !self.fullscreen {
            if !pressed {
                // If it was somehow held, release it.
                if let Some(code) = scancode_from_evdev(evdev) {
                    if self.held.remove(&code) {
                        actions.push(InputAction::SendKey {
                            scancode: code.0,
                            extended: code.1,
                            pressed: false,
                        });
                    }
                }
            }
            return actions;
        }

        // Map evdev to scancode.
        let Some(code) = scancode_from_evdev(evdev) else {
            return actions;
        };

        // Physical 'V' key handling when Ctrl is held and clipboard is shared.
        if evdev == 47 && self.ctrl_held && self.share_clipboard {
            if pressed {
                // Check if a Paste event arrived just before this V.
                if let Some((_text, paste_time)) = self.pending_paste.take() {
                    if now.saturating_duration_since(paste_time) <= PASTE_CORRELATION_TIMEOUT {
                        // The Paste action was already emitted by handle_egui_paste;
                        // swallow this V press so it is not typed into the PC.
                        return actions;
                    }
                }
                // Otherwise wait up to PASTE_CORRELATION_TIMEOUT for egui Paste.
                self.pending_v = Some(PendingV {
                    press_time: now,
                    released: false,
                });
                return actions;
            } else {
                if let Some(pending) = &mut self.pending_v {
                    // V released while waiting for Paste. Do not send release before press.
                    pending.released = true;
                    return actions;
                }
                if !self.held.contains(&code) {
                    // V was swallowed by an earlier Paste; do not send unmatched release.
                    return actions;
                }
            }
        }

        // Normal key press or release.
        if pressed {
            self.held.insert(code);
            actions.push(InputAction::SendKey {
                scancode: code.0,
                extended: code.1,
                pressed: true,
            });
        } else if self.held.remove(&code) {
            actions.push(InputAction::SendKey {
                scancode: code.0,
                extended: code.1,
                pressed: false,
            });
        }

        actions
    }

    /// Processes an egui `Event::Paste(text)` event.
    pub fn handle_egui_paste(&mut self, text: String, now: Instant) -> Vec<InputAction> {
        let mut actions = Vec::new();

        if !self.share_clipboard {
            return actions;
        }

        // If physical V is waiting for this Paste, correlate and emit Paste immediately.
        if let Some(_pending) = self.pending_v.take() {
            actions.push(InputAction::Paste(text));
        } else {
            // Otherwise store it briefly in case the physical V arrives shortly after.
            actions.push(InputAction::Paste(text.clone()));
            self.pending_paste = Some((text, now));
        }

        actions
    }

    /// Periodic tick to flush timed out pending V presses.
    pub fn tick(&mut self, now: Instant) -> Vec<InputAction> {
        self.flush_pending(now)
    }

    fn flush_pending(&mut self, now: Instant) -> Vec<InputAction> {
        let mut actions = Vec::new();

        if let Some(pending) = self.pending_v {
            if now.saturating_duration_since(pending.press_time) >= PASTE_CORRELATION_TIMEOUT {
                self.pending_v = None;
                let code = (0x2F, false); // V scancode
                self.held.insert(code);
                actions.push(InputAction::SendKey {
                    scancode: code.0,
                    extended: code.1,
                    pressed: true,
                });
                if pending.released {
                    self.held.remove(&code);
                    actions.push(InputAction::SendKey {
                        scancode: code.0,
                        extended: code.1,
                        pressed: false,
                    });
                }
            }
        }

        if let Some((_, paste_time)) = self.pending_paste {
            if now.saturating_duration_since(paste_time) >= PASTE_CORRELATION_TIMEOUT {
                self.pending_paste = None;
            }
        }

        actions
    }

    /// True if any keys are currently sent as pressed to the PC.
    #[must_use]
    pub fn has_held_keys(&self) -> bool {
        !self.held.is_empty()
    }

    /// Whether either Left Alt or Right Alt is currently held down.
    #[must_use]
    pub fn is_alt_held(&self) -> bool {
        self.alt_held
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn evdev_scancode_table_mappings() {
        // Table verification required by plan:
        assert_eq!(scancode_from_evdev(83), Some((0x53, false))); // KP .
        assert_eq!(scancode_from_evdev(55), Some((0x37, false))); // KP *
        assert_eq!(scancode_from_evdev(96), Some((0x1C, true))); // KP Enter
        assert_eq!(scancode_from_evdev(98), Some((0x35, true))); // KP /
        assert_eq!(scancode_from_evdev(100), Some((0x38, true))); // AltGr / Right Alt
        assert_eq!(scancode_from_evdev(97), Some((0x1D, true))); // Right Ctrl
        assert_eq!(scancode_from_evdev(74), Some((0x4A, false))); // KP -
        assert_eq!(scancode_from_evdev(78), Some((0x4E, false))); // KP +
        assert_eq!(scancode_from_evdev(99), Some((0x37, true))); // Print Screen

        // Lock keys must produce None
        assert_eq!(scancode_from_evdev(58), None); // Caps Lock
        assert_eq!(scancode_from_evdev(69), None); // Num Lock
        assert_eq!(scancode_from_evdev(70), None); // Scroll Lock

        // Pause/Break produces None (requires E1 sequence not fitting in Scancode)
        assert_eq!(scancode_from_evdev(119), None);
    }

    #[test]
    fn similar_scancodes_are_distinguished() {
        // evdev 55 is keypad asterisk: unextended 0x37
        // evdev 99 is Print Screen: extended 0x37
        assert_eq!(scancode_from_evdev(55), Some((0x37, false)));
        assert_eq!(scancode_from_evdev(99), Some((0x37, true)));
    }

    #[test]
    fn toggle_fullscreen_shortcut() {
        let mut state = KeyState::new(false, true);
        let t0 = Instant::now();

        // Press Left Ctrl (29)
        state.handle_physical_key(29, true, t0);
        // Press Left Alt (56)
        state.handle_physical_key(56, true, t0);
        // Press Enter (28)
        let actions = state.handle_physical_key(28, true, t0);

        assert_eq!(actions, vec![InputAction::ToggleFullscreen]);
        // Enter should not be in held keys
        assert!(!state.held.contains(&(0x1C, false)));
    }

    #[test]
    fn desktop_keys_in_window_vs_fullscreen() {
        let mut state = KeyState::new(false, true); // Windowed
        let t0 = Instant::now();

        // Windows key in windowed mode: ignored
        let actions = state.handle_physical_key(125, true, t0);
        assert!(actions.is_empty());

        // In full screen: sent to PC
        state.set_fullscreen(true);
        let actions = state.handle_physical_key(125, true, t0);
        assert_eq!(
            actions,
            vec![InputAction::SendKey {
                scancode: 0x5B,
                extended: true,
                pressed: true,
            }]
        );
    }

    #[test]
    fn paste_after_v_correlation() {
        let mut state = KeyState::new(true, true);
        let t0 = Instant::now();

        // Press Ctrl (29)
        state.handle_physical_key(29, true, t0);

        // Press V (47) at t0 -> waits for paste
        let actions = state.handle_physical_key(47, true, t0);
        assert!(actions.is_empty());

        // Paste arrives at t0 + 50ms
        let t1 = t0 + Duration::from_millis(50);
        let actions = state.handle_egui_paste("hello".to_string(), t1);
        assert_eq!(actions, vec![InputAction::Paste("hello".to_string())]);

        // Tick at t0 + 200ms: no delayed V should be sent
        let t2 = t0 + Duration::from_millis(200);
        let actions = state.tick(t2);
        assert!(actions.is_empty());
    }

    #[test]
    fn paste_before_v_correlation() {
        let mut state = KeyState::new(true, true);
        let t0 = Instant::now();

        // Press Ctrl (29)
        state.handle_physical_key(29, true, t0);

        // Paste arrives at t0
        let actions = state.handle_egui_paste("world".to_string(), t0);
        assert_eq!(actions, vec![InputAction::Paste("world".to_string())]);

        // Physical V arrives at t0 + 50ms: swallowed, no SendKey
        let t1 = t0 + Duration::from_millis(50);
        let actions = state.handle_physical_key(47, true, t1);
        assert!(actions.is_empty());
    }

    #[test]
    fn paste_timeout_sends_v() {
        let mut state = KeyState::new(true, true);
        let t0 = Instant::now();

        // Press Ctrl (29)
        state.handle_physical_key(29, true, t0);

        // Press V (47) at t0
        let actions = state.handle_physical_key(47, true, t0);
        assert!(actions.is_empty());

        // No Paste arrives. Tick at t0 + 160ms -> V is sent as key press
        let t1 = t0 + Duration::from_millis(160);
        let actions = state.tick(t1);
        assert_eq!(
            actions,
            vec![InputAction::SendKey {
                scancode: 0x2F,
                extended: false,
                pressed: true,
            }]
        );
    }

    #[test]
    fn v_released_while_waiting_for_paste_never_sends_release_first() {
        let mut state = KeyState::new(true, true);
        let t0 = Instant::now();

        // Press Ctrl (29)
        state.handle_physical_key(29, true, t0);

        // Press V (47) at t0
        state.handle_physical_key(47, true, t0);

        // Release V at t0 + 40ms while still waiting
        let t1 = t0 + Duration::from_millis(40);
        let actions = state.handle_physical_key(47, false, t1);
        assert!(actions.is_empty()); // release not sent yet!

        // Timeout expires at t0 + 160ms: must send press THEN release, never release first
        let t2 = t0 + Duration::from_millis(160);
        let actions = state.tick(t2);
        assert_eq!(
            actions,
            vec![
                InputAction::SendKey {
                    scancode: 0x2F,
                    extended: false,
                    pressed: true,
                },
                InputAction::SendKey {
                    scancode: 0x2F,
                    extended: false,
                    pressed: false,
                }
            ]
        );
    }

    #[test]
    fn keys_pressed_on_enter_are_ignored() {
        let mut state = KeyState::new(false, true);
        let t0 = Instant::now();

        // Key A (evdev 30) was already held down when window received focus
        state.handle_enter(&[30]);

        // Press event for 30 ignored
        let actions = state.handle_physical_key(30, true, t0);
        assert!(actions.is_empty());

        // Release event for 30 ignored (no unmatched release sent to PC)
        let actions = state.handle_physical_key(30, false, t0);
        assert!(actions.is_empty());
    }

    #[test]
    fn focus_leave_releases_all_held_keys() {
        let mut state = KeyState::new(true, true);
        let t0 = Instant::now();

        // Press A (30) and S (31)
        state.handle_physical_key(30, true, t0);
        state.handle_physical_key(31, true, t0);
        assert!(state.has_held_keys());

        // Focus lost: all held keys are released
        let actions = state.handle_leave();
        assert_eq!(actions.len(), 2);
        assert!(!state.has_held_keys());
        assert!(actions.iter().all(|a| match a {
            InputAction::SendKey { pressed, .. } => !pressed,
            _ => false,
        }));
    }

    #[test]
    fn physical_source_clipboard_events_do_not_duplicate_keys() {
        let mut state = KeyState::new(true, true);
        let t0 = Instant::now();

        // When Ctrl+C is pressed physically:
        state.handle_physical_key(29, true, t0); // Ctrl
        let actions = state.handle_physical_key(46, true, t0); // C
        assert_eq!(
            actions,
            vec![InputAction::SendKey {
                scancode: 0x2E,
                extended: false,
                pressed: true,
            }]
        );

        // When Ctrl+X is pressed physically:
        let actions = state.handle_physical_key(45, true, t0); // X
        assert_eq!(
            actions,
            vec![InputAction::SendKey {
                scancode: 0x2D,
                extended: false,
                pressed: true,
            }]
        );

        // When egui sends Paste, it only emits InputAction::Paste, never SendKey
        let paste_actions = state.handle_egui_paste("sample".to_string(), t0);
        assert_eq!(
            paste_actions,
            vec![InputAction::Paste("sample".to_string())]
        );
    }
}
