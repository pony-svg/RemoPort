    fn assert_v_balanced(actions: &[InputAction], expected_pastes: usize) {
        let mut v_depth = 0i32;
        let mut pastes = 0usize;
        let mut releases = 0usize;
        for action in actions {
            match action {
                InputAction::Paste(_) => {
                    pastes += 1;
                    v_depth += 1;
                }
                InputAction::SendKey {
                    scancode: 0x2F,
                    extended: false,
                    pressed: true,
                } => {
                    v_depth += 1;
                }
                InputAction::SendKey {
                    scancode: 0x2F,
                    extended: false,
                    pressed: false,
                } => {
                    releases += 1;
                    v_depth -= 1;
                    assert!(
                        v_depth >= 0,
                        "V release emitted without a preceding press/paste: {actions:?}"
                    );
                }
                _ => {}
            }
        }
        assert_eq!(
            pastes, expected_pastes,
            "unexpected paste count: {actions:?}"
        );
        assert_eq!(v_depth, 0, "V left pressed on PC: {actions:?}");
        assert_eq!(
            releases, pastes,
            "V releases must match V presses: {actions:?}"
        );
    }

